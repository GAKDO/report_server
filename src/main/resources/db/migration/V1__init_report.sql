-- report 스키마 시작점: GAKDO/docs db/V1__init.sql의 report 절 그대로
CREATE SCHEMA IF NOT EXISTS report;

CREATE TABLE report.record_chain (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rental_id      varchar(21) NOT NULL,
  checkpoint_id  varchar(21) NOT NULL,
  seq            integer  NOT NULL,
  payload_hash   char(64) NOT NULL,
  prev_hash      char(64),
  signature      text     NOT NULL,
  signed_at      timestamptz NOT NULL,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  UNIQUE (rental_id, seq)
);

CREATE TABLE report.report (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rental_id     varchar(21) NOT NULL UNIQUE,
  verify_token  char(32) NOT NULL UNIQUE,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE report.report_view (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rental_id   varchar(21)  NOT NULL UNIQUE,
  timeline    jsonb NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

