-- RP1: 해시 체인 기록에 검증 재료를 더하고, 이벤트로 만드는 시점 읽기 모델·멱등·수동 봉인 사용 기록을 둔다.
-- (docs design/ddl.md report 절에 같이 적음)

-- 체인 한 줄: 무엇을 봉인했는지(payload 원문)와 그 줄의 해시(record_hash = 다음 줄의 prev_hash)를 남긴다
ALTER TABLE report.record_chain
  ADD COLUMN checkpoint_type varchar(3) NOT NULL CHECK (checkpoint_type IN ('OUT','RCV','RET')),
  ADD COLUMN grade           char(1)    NOT NULL CHECK (grade IN ('A','B','C','D')),
  ADD COLUMN payload         jsonb      NOT NULL,          -- payload_hash의 원문(정규화 JSON으로 다시 계산)
  ADD COLUMN record_hash     char(64)   NOT NULL,          -- 이 줄 해시. 다음 줄 prev_hash, Ed25519 서명 대상
  ADD COLUMN manual          boolean    NOT NULL DEFAULT false,  -- 관리자 수동 봉인(시연 우회로)
  ADD CONSTRAINT record_chain_checkpoint_uk UNIQUE (checkpoint_id),
  ADD CONSTRAINT record_chain_type_uk UNIQUE (rental_id, checkpoint_type);

-- 시점 읽기 모델: capture.uploaded·checkpoint.graded·diagnostics.recorded로 채운다
CREATE TABLE report.checkpoint_view (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rental_id          varchar(21) NOT NULL,
  checkpoint_id      varchar(21) NOT NULL UNIQUE,
  checkpoint_type    varchar(3)  CHECK (checkpoint_type IN ('OUT','RCV','RET')),  -- graded·수동 봉인 때 알게 된다
  status             varchar(8)  NOT NULL CHECK (status IN ('OPEN','CAPTURED','GRADED','SEALED')),
  occurred_at        timestamptz,                         -- 촬영 업로드 완료 시각
  capture_set_id     varchar(21),
  photos             jsonb NOT NULL DEFAULT '[]',          -- capture.uploaded photos[photoId, face, light, camera, objectKey, sha256]
  chain_photos       jsonb NOT NULL DEFAULT '[]',          -- graded photos[photoId, sha256] = 해시 체인 재료
  grade              char(1) CHECK (grade IN ('A','B','C','D')),
  rule_version       varchar(32),
  new_defect_ids     jsonb NOT NULL DEFAULT '[]',
  unjudgeable_faces  jsonb NOT NULL DEFAULT '[]',
  graded_at          timestamptz,
  diag_run_id        varchar(21),
  diag_sha256        char(64),
  diag_flags         jsonb NOT NULL DEFAULT '[]',          -- 플래그 종류(kind)만
  sealed_at          timestamptz,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX checkpoint_view_rental_idx ON report.checkpoint_view (rental_id);
CREATE INDEX checkpoint_view_due_idx ON report.checkpoint_view (status, graded_at) WHERE status = 'GRADED';

-- 같은 eventId가 다시 와도 한 번만 처리한다
CREATE TABLE report.processed_event (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id     varchar(21) NOT NULL UNIQUE,
  routing_key  varchar(64) NOT NULL,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now()
);

-- 관리자 수동 봉인 사용 기록(11/2 결정)
CREATE TABLE report.manual_seal_log (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rental_id        varchar(21) NOT NULL,
  checkpoint_id    varchar(21) NOT NULL UNIQUE,
  checkpoint_type  varchar(3)  NOT NULL CHECK (checkpoint_type IN ('OUT','RCV','RET')),
  grade            char(1)     NOT NULL CHECK (grade IN ('A','B','C','D')),
  seq              integer     NOT NULL,
  reason           varchar(300) NOT NULL,
  sealed_by        varchar(64) NOT NULL,                   -- 관리자 JWT sub(계정 publicId)
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now()
);
